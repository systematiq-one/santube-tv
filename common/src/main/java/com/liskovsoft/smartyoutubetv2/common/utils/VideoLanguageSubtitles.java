package com.liskovsoft.smartyoutubetv2.common.utils;

import com.google.android.exoplayer2.util.Util;
import com.liskovsoft.mediaserviceinterfaces.data.MediaFormat;
import com.liskovsoft.mediaserviceinterfaces.data.MediaItemFormatInfo;
import com.liskovsoft.mediaserviceinterfaces.data.MediaSubtitle;
import com.liskovsoft.sharedutils.helpers.Helpers;
import com.liskovsoft.smartyoutubetv2.common.exoplayer.selector.FormatItem;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Picks the captions in the language the video is spoken in, so one press on the captions
 * button is enough.<br/>
 * The player's own subtitle list can't answer this: YouTube marks autogenerated and auto
 * translated tracks alike with a trailing '*', and the tracks are sorted by name before they
 * reach the player, so neither the marker nor the position identifies the original. The format
 * info behind the manifest does — every translation is the origin track's url plus a 'tlang'
 * query, and the original audio track names the video's language.
 */
public final class VideoLanguageSubtitles {
    /** {@code CaptionTrack.TYPE_ASR} — autogenerated captions. The constant itself is private. */
    private static final String TYPE_ASR = "asr";
    /** Audio track ids look like "en-US.4": the language, then the kind of track (4 - original) */
    private static final String ORIGINAL_AUDIO_SUFFIX = ".4";
    private static final String ENGLISH = "en";

    private VideoLanguageSubtitles() {
    }

    /**
     * The player's subtitle track that matches {@link #findOrigin(MediaItemFormatInfo)}.
     *
     * @param formats the tracks the player offers ({@code PlayerEngine.getSubtitleFormats()})
     * @return null when the video has no captions of its own or the source carried no track metadata
     */
    public static FormatItem findFormat(MediaItemFormatInfo formatInfo, List<FormatItem> formats) {
        if (formats == null) {
            return null;
        }

        String language = getTrackLanguage(findOrigin(formatInfo));

        if (language == null) {
            return null;
        }

        for (FormatItem format : formats) {
            if (format != null && !format.isDefault() && Helpers.equals(language, format.getLanguage())) {
                return format;
            }
        }

        return null;
    }

    /**
     * The autogenerated captions in the video's own language, then the English autogenerated
     * ones, then any autogenerated track, then the video's own captions when it has none.<br/>
     * Auto-dubbed videos carry an extra autogenerated track per dub (the dub's transcript), listed
     * by localized name, so taking the first one picks e.g. Arabic on a video spoken in English.
     * The video's language comes from the original audio track, the dubbed languages from the rest.<br/>
     * Translations are listed after the real caption tracks, so the first untranslated one is the
     * origin — which also covers the translation into the origin's own language, the one case
     * where a translation carries no 'tlang' of its own.
     */
    public static MediaSubtitle findOrigin(MediaItemFormatInfo formatInfo) {
        if (formatInfo == null || formatInfo.getSubtitles() == null) {
            return null;
        }

        String videoLanguage = null;
        List<String> dubbedLanguages = new ArrayList<>();

        if (formatInfo.getAdaptiveFormats() != null) {
            for (MediaFormat format : formatInfo.getAdaptiveFormats()) {
                String audioTrackId = format != null ? format.getAudioTrackId() : null;

                if (audioTrackId == null) {
                    continue;
                }

                String language = baseLanguage(audioTrackId);

                if (audioTrackId.endsWith(ORIGINAL_AUDIO_SUFFIX)) {
                    videoLanguage = language;
                } else if (!dubbedLanguages.contains(language)) {
                    dubbedLanguages.add(language);
                }
            }
        }

        MediaSubtitle videoLanguageAsr = null;
        MediaSubtitle englishAsr = null;
        MediaSubtitle firstAsr = null;
        MediaSubtitle firstOrigin = null;

        for (MediaSubtitle sub : formatInfo.getSubtitles()) {
            if (sub == null || isTranslation(sub)) {
                continue;
            }

            if (firstOrigin == null) {
                firstOrigin = sub;
            }

            if (!TYPE_ASR.equals(sub.getType())) {
                continue;
            }

            if (firstAsr == null) {
                firstAsr = sub;
            }

            String language = baseLanguage(sub.getLanguageCode());

            if (videoLanguage != null && videoLanguage.equals(language)) {
                if (videoLanguageAsr == null || isDubTranscript(videoLanguageAsr)) {
                    videoLanguageAsr = sub;
                }
            } else if (videoLanguage == null && !isDubTranscript(sub) && !dubbedLanguages.contains(language)) {
                // No original audio track to go by: the transcript that isn't of a dub
                if (videoLanguageAsr == null) {
                    videoLanguageAsr = sub;
                }
            }

            if (ENGLISH.equals(language) && (englishAsr == null || isDubTranscript(englishAsr))) {
                englishAsr = sub;
            }
        }

        if (videoLanguageAsr != null) {
            return videoLanguageAsr;
        }

        if (englishAsr != null) {
            return englishAsr;
        }

        return firstAsr != null ? firstAsr : firstOrigin;
    }

    /**
     * Both manifest builders hand the track's name to ExoPlayer as the track language, and the
     * Format constructor normalizes it (lowercase, among other things) before storing it.
     * Run it through the very same call or the comparison never matches.
     */
    static String getTrackLanguage(MediaSubtitle sub) {
        if (sub == null) {
            return null;
        }

        return Util.normalizeLanguageCode(sub.getName() != null ? sub.getName() : sub.getLanguageCode());
    }

    /**
     * Autogenerated track made from an auto-dubbed audio track
     */
    private static boolean isDubTranscript(MediaSubtitle sub) {
        return sub.getBaseUrl() != null && sub.getBaseUrl().contains("variant=timing-optimized");
    }

    private static boolean isTranslation(MediaSubtitle sub) {
        return sub.getBaseUrl() != null && sub.getBaseUrl().contains("tlang=");
    }

    /**
     * "en-US.4" or "en-US" -> "en"
     */
    static String baseLanguage(String code) {
        if (code == null) {
            return null;
        }

        int end = code.length();

        for (int i = 0; i < code.length(); i++) {
            char c = code.charAt(i);

            if (c == '-' || c == '_' || c == '.') {
                end = i;
                break;
            }
        }

        return code.substring(0, end).toLowerCase(Locale.ROOT);
    }
}
